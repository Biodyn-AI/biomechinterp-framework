#!/usr/bin/env python3
"""Analyze per-perturbation recall concentration for top bridge methods."""

from __future__ import annotations

import argparse
import warnings
from pathlib import Path

import matplotlib
import pandas as pd

from network_inference.src.evaluation.perturbation import evaluate_perturbations

matplotlib.use("Agg")
import matplotlib.pyplot as plt  # noqa: E402


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--repo-root",
        type=Path,
        default=Path(__file__).resolve().parents[3],
        help="Repository root.",
    )
    parser.add_argument(
        "--benchmark-csv",
        type=Path,
        default=Path(
            "subproject_07_perturbation_to_network_bridging/reports/artifacts/bridge_benchmark/bridge_eval_metrics.csv"
        ),
        help="Bridge benchmark CSV generated by run_bridge_benchmark.py.",
    )
    parser.add_argument(
        "--top-k-methods",
        type=int,
        default=6,
        help="How many top methods (by perturbation_edges F1) to analyze.",
    )
    parser.add_argument(
        "--extra-methods",
        type=str,
        default="base,regulatory,omnipath_dorothea_intersection_immune_hpn",
        help="Comma-separated methods to force-include.",
    )
    parser.add_argument(
        "--output-dir",
        type=Path,
        default=Path(
            "subproject_07_perturbation_to_network_bridging/reports/artifacts/bridge_benchmark"
        ),
        help="Output directory for concentration tables/figures.",
    )
    return parser.parse_args()


def gini(values: list[float]) -> float:
    if not values:
        return 0.0
    sorted_vals = sorted(v for v in values if v >= 0)
    n = len(sorted_vals)
    if n == 0:
        return 0.0
    total = sum(sorted_vals)
    if total == 0:
        return 0.0
    cum = 0.0
    for idx, val in enumerate(sorted_vals, start=1):
        cum += idx * val
    return (2 * cum) / (n * total) - (n + 1) / n


def main() -> None:
    args = parse_args()
    repo_root = args.repo_root.resolve()
    benchmark_csv = (
        args.benchmark_csv if args.benchmark_csv.is_absolute() else (repo_root / args.benchmark_csv)
    ).resolve()
    output_dir = args.output_dir if args.output_dir.is_absolute() else (repo_root / args.output_dir)
    output_dir = output_dir.resolve()
    output_dir.mkdir(parents=True, exist_ok=True)

    warnings.filterwarnings("ignore", category=FutureWarning)
    warnings.filterwarnings("ignore", category=UserWarning)

    metrics = pd.read_csv(benchmark_csv)
    pert = metrics[metrics["reference"] == "perturbation_edges"].copy()
    top_methods = pert.sort_values(["f1", "aupr"], ascending=False)["method"].head(args.top_k_methods).tolist()
    forced = [m.strip() for m in args.extra_methods.split(",") if m.strip()]
    method_order = []
    for name in top_methods + forced:
        if name not in method_order and name in set(pert["method"].tolist()):
            method_order.append(name)

    processed_h5ad = repo_root / "single_cell_mechinterp/outputs/tabula_sapiens_immune_subset_hpn_processed.h5ad"
    hgnc_alias_tsv = repo_root / "single_cell_mechinterp/external/hgnc_complete_set.txt"
    perturbation_tsv = repo_root / "network_inference/data/timeseries_edges.tsv"

    summary_rows = []
    detail_rows = []
    for method in method_order:
        edge_file = pert.loc[pert["method"] == method, "edge_file"].iloc[0]
        pred_edges_path = repo_root / "network_inference/outputs" / edge_file
        result = evaluate_perturbations(
            pred_edges_path=pred_edges_path,
            perturbation_tsv=perturbation_tsv,
            processed_h5ad=processed_h5ad,
            hgnc_alias_tsv=hgnc_alias_tsv,
            source_col="source",
            target_col="target",
            perturbation_col="source",
        )

        per = pd.DataFrame(result["per_perturbation_recall"])
        per["method"] = method
        per["edge_file"] = edge_file
        detail_rows.append(per)

        recalls = per["recall"].tolist()
        nonzero = int((per["recall"] > 0).sum())
        summary_rows.append(
            {
                "method": method,
                "edge_file": edge_file,
                "n_perturbations": int(per.shape[0]),
                "nonzero_perturbations": nonzero,
                "nonzero_pct": float(nonzero / per.shape[0]) if per.shape[0] else 0.0,
                "avg_recall": float(result["avg_recall"]),
                "median_recall": float(per["recall"].median()) if per.shape[0] else 0.0,
                "p90_recall": float(per["recall"].quantile(0.9)) if per.shape[0] else 0.0,
                "max_recall": float(per["recall"].max()) if per.shape[0] else 0.0,
                "gini_recall": float(gini(recalls)),
                "overall_precision": float(result["overall_metrics"]["precision"]),
                "overall_recall": float(result["overall_metrics"]["recall"]),
                "overall_f1": float(result["overall_metrics"]["f1"]),
                "overall_aupr": float(result["overall_metrics"]["aupr"]),
            }
        )

    summary = pd.DataFrame(summary_rows).sort_values(["overall_f1", "overall_aupr"], ascending=False)
    detail = pd.concat(detail_rows, ignore_index=True) if detail_rows else pd.DataFrame()
    summary.to_csv(output_dir / "perturbation_recall_concentration_summary.csv", index=False)
    detail.to_csv(output_dir / "perturbation_recall_concentration_detail.csv", index=False)

    # Figure: sorted recall curves to show concentration shape per method.
    plt.figure(figsize=(9, 6))
    for method in summary["method"].tolist():
        method_rows = detail[detail["method"] == method].copy()
        vals = method_rows["recall"].sort_values(ascending=False).reset_index(drop=True)
        if vals.empty:
            continue
        x = range(1, len(vals) + 1)
        plt.plot(x, vals.values, label=method, linewidth=1.2)
    plt.xlabel("Perturbations (sorted by recall)")
    plt.ylabel("Per-perturbation recall")
    plt.title("Recall Concentration Across Perturbations")
    plt.legend(fontsize=7, ncol=2)
    plt.tight_layout()
    plt.savefig(output_dir / "perturbation_recall_concentration_curves.png", dpi=220)
    plt.close()


if __name__ == "__main__":
    main()
